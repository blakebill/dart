let currentLang = 'zh';

function setLang(lang) {
  currentLang = DICT[lang] ? lang : 'zh';
}

function getLang() {
  return currentLang;
}

/** Translate a key with optional {0},{1}... placeholder substitution. */
function t(key, ...args) {
  const table = DICT[currentLang] || DICT.zh;
  let str = table[key];
  if (str === undefined) str = (DICT.zh[key] !== undefined ? DICT.zh[key] : key);
  return str.replace(/\{(\d+)\}/g, (_, i) => (args[i] !== undefined ? args[i] : ''));
}

/** Apply translations to all elements marked with data-i18n / data-i18n-ph. */
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
  document.title = t('appName');
}

window.i18n = { t, setLang, getLang, applyI18n, DICT };
